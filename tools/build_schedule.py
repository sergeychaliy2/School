def build(table, grades):
    out = {g: {d: [] for d in DAYS} for g in grades}
    for day, rows in table.items():
        for lesson_no, row in enumerate(rows, start=1):
            for column, cell in enumerate(row):
                subject, _, room = cell.partition("|")
                subject = subject.strip()
                if not subject:
                    continue
                item = {"n": lesson_no, "subject": subject, "room": room.strip() or None}
                if subject == "Профориентация":
                    item["note"] = "Россия – мои горизонты"
                out[grades[column]][day].append(item)
    return out


